// One-off: freeze poseidon-lite's t=4 and t=5 constants into our source as hex.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire(new URL('../../../packages/universe/package.json', import.meta.url));
const dir = require.resolve('poseidon-lite').replace(/index\.js$/, '');
const unstr = require(dir + 'poseidon/unstringify.js').default;
let out = '// Generated by apps/tools/src/extract-constants.mjs from poseidon-lite@0.3.0. Frozen (spec v1).\n';
for (const n of [3, 4]) {
  const c = unstr(require(dir + `constants/${n}.js`).default);
  out += `export const C${n + 1} = ${JSON.stringify(c.C.map((x) => '0x' + x.toString(16)))};\n`;
  out += `export const M${n + 1} = ${JSON.stringify(c.M.map((r) => r.map((x) => '0x' + x.toString(16))))};\n`;
}
writeFileSync(new URL('../../../packages/universe/src/poseidon-constants.ts', import.meta.url), out);
